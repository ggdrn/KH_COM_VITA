static const Glyph* FindGlyph(char ch) {
    size_t i;

    for (i = 0; i < sizeof(sFont) / sizeof(sFont[0]); i++) {
        if (sFont[i].ch == ch) {
            return &sFont[i];
        }
    }
    return NULL;
}

void TextFill(uint32_t* canvas, int cw, int ch, int x, int y, int w, int h, uint32_t rgba) {
    int i, j;

    for (j = y; j < y + h && j < ch; j++) {
        for (i = x; i < x + w && i < cw; i++) {
            if (i >= 0 && j >= 0) {
                canvas[j * cw + i] = rgba;
            }
        }
    }
}

/* Text at `scale` canvas pixels per font pixel (6 x 8 cells per character). */
void TextDraw(uint32_t* canvas, int cw, int ch, int x, int y, const char* s, uint32_t rgba, int scale) {
    for (; *s; s++, x += 6 * scale) {
        const Glyph* g = FindGlyph(*s);
        int r, c;

        if (g == NULL) {
            continue;
        }
        for (r = 0; r < 7; r++) {
            for (c = 0; c < 5; c++) {
                if (g->rows[r][c] == '#') {
                    TextFill(canvas, cw, ch, x + c * scale, y + r * scale, scale, scale, rgba);
                }
            }
        }
    }
}

int TextWidth(const char* s, int scale) {
    return (int)strlen(s) * 6 * scale - scale;
}
